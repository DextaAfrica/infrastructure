#!/usr/bin/env bash
# ==============================================================================
# Dexta Africa Traefik Maintenance Mode CLI Controller
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="$ROOT_DIR/.env"
DYNAMIC_DIR="$ROOT_DIR/docker/traefik/dynamic"
MAINTENANCE_YML="$DYNAMIC_DIR/maintenance.yml"

mkdir -p "$DYNAMIC_DIR"

if [ -f "$ENV_FILE" ]; then
    set -a
    # shellcheck disable=SC1090,SC1091
    source "$ENV_FILE"
    set +a
fi

DOMAIN="${DOMAIN:-dextaafrica.com}"
WWW_DOMAIN="${WWW_DOMAIN:-www.dextaafrica.com}"
ADMIN_DOMAIN="${ADMIN_DOMAIN:-admin.dextaafrica.com}"
OPS_DOMAIN="${OPS_DOMAIN:-ops.dextaafrica.com}"
API_DOMAIN="${API_DOMAIN:-api.dextaafrica.com}"
BYPASS_CIDR="${MAINTENANCE_BYPASS_CIDR:-}"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

ACTION="${1:-status}"

case "$ACTION" in
    on|enable|start)
        echo -e "${YELLOW}==>${NC} Enabling Enterprise Maintenance Mode via Traefik router..."

        RULE="Host(\`${DOMAIN}\`) || Host(\`${WWW_DOMAIN}\`) || Host(\`${ADMIN_DOMAIN}\`) || Host(\`${OPS_DOMAIN}\`)"
        if [ -n "$BYPASS_CIDR" ]; then
            RULE="!ClientIP(\`${BYPASS_CIDR}\`) && (${RULE})"
            echo -e "         Whitelisted bypass CIDR: ${GREEN}${BYPASS_CIDR}${NC}"
        fi

        cat <<EOF > "$MAINTENANCE_YML"
# Autogenerated by scripts/maintenance.sh - DO NOT EDIT MANUALLY
http:
  routers:
    maintenance-router:
      rule: "${RULE}"
      entryPoints:
        - websecure
      priority: 99999
      service: maintenance-service
      tls:
        certResolver: letsencrypt
      middlewares:
        - secHeaders

  services:
    maintenance-service:
      loadBalancer:
        servers:
          - url: "http://maintenance-page:80"
EOF

        echo -e "${GREEN}[ACTIVE]${NC} Maintenance mode is now ENABLED."
        echo -e "         Traefik is routing public visitors to the branded 503 maintenance page."
        ;;

    off|disable|stop)
        echo -e "${BLUE}==>${NC} Disabling Enterprise Maintenance Mode in Traefik..."
        rm -f "$MAINTENANCE_YML"
        echo -e "${GREEN}[INACTIVE]${NC} Maintenance mode is now DISABLED."
        echo -e "           Traefik has restored live traffic to all application services."
        ;;

    status)
        if [ -f "$MAINTENANCE_YML" ]; then
            echo -e "${YELLOW}[STATUS]${NC} Maintenance mode is currently: ${RED}ACTIVE${NC} (Branded 503 page rendering)"
        else
            echo -e "${GREEN}[STATUS]${NC} Maintenance mode is currently: ${GREEN}INACTIVE${NC} (Live traffic serving)"
        fi
        ;;

    *)
        echo "Usage: $0 {on|off|status}"
        exit 1
        ;;
esac
